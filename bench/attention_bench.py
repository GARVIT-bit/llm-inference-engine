"""Benchmark: Triton fused causal attention vs PyTorch attention (CUDA only; run on Colab).

Shapes follow GPT-2: H=12 heads, D=64, batch 2, fp16, sequence length 256..4096.
  - pytorch naive : q @ k^T, causal mask, softmax (fp32), @ v  -- materialises [T, T] scores
  - triton fused  : kernels/attention_triton.py (tiled, online softmax, causal)
  - torch SDPA    : torch's built-in fused attention, as a REFERENCE POINT ONLY
                    (the engine never uses it; CLAUDE.md rule)
Reports median time (round-robin, after warm-up, CUDA-synchronised), achieved TFLOP/s
(causal: 2 * 2 * B * H * T^2 * D / 2 flops), peak extra GPU memory, and max abs error
against an fp32 reference.

    python bench/attention_bench.py --out attention_t4
"""
from __future__ import annotations

import argparse
import csv
import math
import sys
from pathlib import Path

import torch

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from bench.common import RESULTS, machine_info, machine_md, time_interleaved  # noqa: E402
from kernels.attention_triton import HAS_TRITON, triton_attention  # noqa: E402


def naive_attention(q, k, v, mask):
    s = (q @ k.transpose(-1, -2)) * (1.0 / math.sqrt(q.shape[-1]))
    s = s.masked_fill(mask, float("-inf"))
    return torch.softmax(s.float(), dim=-1).to(q.dtype) @ v


def peak_mb(fn) -> float:
    torch.cuda.synchronize()
    torch.cuda.reset_peak_memory_stats()
    base = torch.cuda.memory_allocated()
    fn()
    torch.cuda.synchronize()
    return (torch.cuda.max_memory_allocated() - base) / 2**20


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--lengths", default="256,512,1024,2048,4096")
    ap.add_argument("--batch", type=int, default=2)
    ap.add_argument("--heads", type=int, default=12)
    ap.add_argument("--dim", type=int, default=64)
    ap.add_argument("--runs", type=int, default=20)
    ap.add_argument("--out", default="attention_t4")
    args = ap.parse_args()
    if not HAS_TRITON:
        sys.exit("needs Triton + a CUDA GPU: run this in bench/colab_gpu.ipynb")
    torch.manual_seed(0)
    B, H, D = args.batch, args.heads, args.dim
    rows = []
    for T in [int(x) for x in args.lengths.split(",")]:
        q, k, v = (torch.randn(B, H, T, D, device="cuda", dtype=torch.float16) for _ in range(3))
        mask = torch.ones(T, T, device="cuda", dtype=torch.bool).triu(1)
        ref = naive_attention(q.float(), k.float(), v.float(), mask)
        fns = {
            "pytorch naive": lambda: naive_attention(q, k, v, mask),
            "triton fused": lambda: triton_attention(q, k, v, causal=True),
            "torch SDPA (reference only)": lambda: torch.nn.functional.scaled_dot_product_attention(q, k, v, is_causal=True),
        }
        ok = {}
        for name, fn in list(fns.items()):
            try:
                out = fn()
                torch.cuda.synchronize()
                ok[name] = ((out.float() - ref).abs().max().item(), peak_mb(fn))
            except torch.cuda.OutOfMemoryError:
                torch.cuda.empty_cache()
                del fns[name]
                ok[name] = None
        del ref
        timing = time_interleaved(fns, runs=args.runs, sync=torch.cuda.synchronize)
        flops = 2 * 2 * B * H * T * T * D / 2
        for name in ok:
            r = {"seq_len": T, "method": name}
            if ok[name] is None:
                r.update(ms="OOM", ms_min="", ms_max="", tflops="", peak_mb="", max_abs_err="")
            else:
                s = timing[name]
                r.update(ms=round(1e3 * s["median"], 4), ms_min=round(1e3 * s["min"], 4),
                         ms_max=round(1e3 * s["max"], 4), tflops=round(flops / s["median"] / 1e12, 3),
                         peak_mb=round(ok[name][1], 1), max_abs_err=f"{ok[name][0]:.2e}")
            rows.append(r)
            print(r, flush=True)
        del q, k, v, mask
        torch.cuda.empty_cache()

    RESULTS.mkdir(parents=True, exist_ok=True)
    with open(RESULTS / f"{args.out}.csv", "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0]))
        w.writeheader()
        w.writerows(rows)
    lines = ["# Fused causal attention: Triton vs PyTorch", "",
             f"Generated by `bench/attention_bench.py`. batch {B}, {H} heads, head dim {D}, fp16, causal. "
             f"{args.runs} runs per config, round-robin after warm-up, CUDA-synchronised; median (min to max). "
             "Error = max abs difference from an fp32 naive reference. Peak = extra GPU memory allocated "
             "during one call. torch SDPA is shown as a reference point only; the engine does not use it.", "",
             "## Machine", machine_md(machine_info()), "",
             "## Results", "",
             "| seq len | method | time (ms) | TFLOP/s | peak extra memory (MB) | max abs error |",
             "|---|---|---|---|---|---|"]
    for r in rows:
        t = r["ms"] if r["ms"] == "OOM" else f"{r['ms']:.3f} ({r['ms_min']:.3f} to {r['ms_max']:.3f})"
        lines.append(f"| {r['seq_len']} | {r['method']} | {t} | {r['tflops']} | {r['peak_mb']} | {r['max_abs_err']} |")
    lines += ["", "## Triton speedup over PyTorch naive", "", "| seq len | speedup | memory ratio |", "|---|---|---|"]
    by = {(r["seq_len"], r["method"]): r for r in rows}
    for T in sorted({r["seq_len"] for r in rows}):
        a, b = by[(T, "pytorch naive")], by[(T, "triton fused")]
        if a["ms"] == "OOM" or b["ms"] == "OOM":
            lines.append(f"| {T} | naive OOM | |")
        else:
            lines.append(f"| {T} | {a['ms'] / b['ms']:.2f}x | {b['peak_mb'] / a['peak_mb']:.3f} |")
    (RESULTS / f"{args.out}.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {RESULTS / (args.out + '.md')}")


if __name__ == "__main__":
    main()
